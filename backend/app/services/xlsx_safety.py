"""Защита от formula injection в генерируемых xlsx-документах.

Итоговые документы (заказ-наряд, накладная) собираются из данных, которые
в конечном счёте пришли из ЗАГРУЖЕННОГО заказчиком файла (наименование
детали/работы из заказ-наряда, догадка LLM по названию и т.п.) — то есть
это не данные, которые ввёл сам пользователь программы через доверенную
форму, а фактически произвольный текст извне. Строка вида
"=CMD('/c calc')" или "@SUM(1+1)*cmd|..." в поле "Наименование", попав как
есть в ячейку через openpyxl, станет формулой (openpyxl сам помечает ячейку
как формулу по ведущему "="), которая выполнится при открытии готового
документа в Excel — в том числе когда этот документ уйдёт клиенту,
страховой или бухгалтеру. См. OWASP CSV/Formula Injection.
"""

from __future__ import annotations

_DANGEROUS_LEADING_CHARS = ("=", "+", "-", "@", "\t", "\r")


def sanitize_cell_value(value):
    """Нейтрализует ведущий формуло-образующий символ в строковых значениях,
    записываемых в ячейку. Не строки (числа, None, datetime и т.п.) не трогает —
    формулой может стать только строка."""
    if not isinstance(value, str) or not value:
        return value
    if value[0] in _DANGEROUS_LEADING_CHARS:
        return "'" + value
    return value
