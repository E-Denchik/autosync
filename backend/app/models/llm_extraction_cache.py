from datetime import datetime

from app.extensions import db


class LlmExtractionCache(db.Model):
    """Кеш результата LLM-извлечения таблицы из ОДНОГО куска текста (см.
    llm_client.py: extract_table_from_text, режет длинный/широкий текст на
    куски и разбирает их по отдельности). Повторная загрузка того же файла
    (частый сценарий при тестировании — то же содержимое, тот же файл
    заново) иначе каждый раз заново оплачивала бы то же самое облачному
    провайдеру (vsegpt.ru) и заново тратила время на локальный.

    Ключ — хеш содержимого куска + запрошенных полей + провайдера/модели
    (не просто "весь файл целиком"): тот же кусок текста, попавшийся в
    ДРУГОМ файле, тоже берётся из кеша, а смена модели в настройках
    естественно "сбрасывает" кеш вместо того, чтобы молча подсовывать
    результат от другой/более слабой модели. Хранится в БД, а не в
    памяти процесса (как progress_tracker.py) — это тот случай, когда
    выгода как раз в том, чтобы пережить перезапуск приложения.

    Кешируются только ЧИСТО распарсенные результаты — see llm_client.py:
    обрезанный/восстановленный ответ намеренно не попадает сюда, иначе
    неполный результат застрял бы в кеше навсегда вместо того, чтобы быть
    переспрошенным при следующей обработке."""

    __tablename__ = "llm_extraction_cache"

    id = db.Column(db.Integer, primary_key=True)
    cache_key = db.Column(db.String(64), unique=True, nullable=False, index=True)
    rows = db.Column(db.JSON, nullable=False)
    created_at = db.Column(db.DateTime, default=datetime.utcnow, nullable=False)

    def __repr__(self):
        return f"<LlmExtractionCache {self.cache_key[:12]}…>"
